'use strict';
// Escribe lo que lee Claude (y cualquier persona) en la carpeta .soulgraph/:
//   MAP.md      resumen legible de todo el proyecto, pensado para leerse de una vez
//   graph.json  el grafo completo, un nodo/enlace por línea (fácil de buscar con grep)
//   studio/     copia de solo lectura del código de cada script de Studio
//
// Writes what Claude (and anyone else) reads into the .soulgraph/ folder:
//   MAP.md      readable summary of the whole project, meant to be read in one go
//   graph.json  the full graph, one node/link per line (easy to grep)
//   studio/     read-only copy of every Studio script's source

const fs = require('fs');
const path = require('path');
const { usedByIndex, pathOf } = require('./graph');

const MAX_SYMBOLS = 30; // funciones listadas por archivo / functions listed per file
const COLLAPSE_AT = 12; // a partir de aquí se agrupan archivos iguales / group same-kind files from here

function writeOutputs({ outDir, project, graph, studio }) {
  fs.mkdirSync(outDir, { recursive: true });

  const mirrors = studio.mirrorPaths();
  writeMirrors(path.join(outDir, 'studio'), mirrors, studio.sources);

  writeIfChanged(path.join(outDir, 'graph.json'), graphJson(graph, mirrors));
  writeIfChanged(path.join(outDir, 'MAP.md'), mapMarkdown({ project, graph, studio, mirrors }));
}

// ---------- graph.json ----------

function graphJson(graph, mirrors) {
  const nodes = graph.nodes.map((n) => JSON.stringify(
    mirrors.has(n.id) ? { ...n, mirror: `.soulgraph/studio/${mirrors.get(n.id)}` } : n,
  ));
  const links = graph.links.map((l) => JSON.stringify(l));
  const issues = (graph.issues || []).map((i) => JSON.stringify(i));
  return `{"nodes":[\n${nodes.join(',\n')}\n],"links":[\n${links.join(',\n')}\n],"issues":[\n${issues.join(',\n')}\n]}\n`;
}

// ---------- MAP.md ----------

function mapMarkdown({ project, graph, studio, mirrors }) {
  const byId = new Map(graph.nodes.map((n) => [n.id, n]));
  const usedBy = usedByIndex(graph);
  const disk = graph.nodes.filter((n) => n.source === 'disk');
  const live = graph.nodes.filter((n) => n.source === 'studio');
  const label = (n) => pathOf(n, byId);

  const out = [];
  out.push(`# SoulGraph map — ${project}`);
  out.push('');
  out.push('> Auto-generated by SoulGraph. Do not edit by hand. / Generado automáticamente por SoulGraph, no editar a mano.');
  out.push('');
  out.push(`- Updated / Actualizado: ${new Date().toISOString()}`);
  const { sessions } = studio.status();
  if (!sessions.length) out.push('- Roblox Studio: never synced / nunca sincronizado');
  for (const s of sessions) {
    const seen = s.lastSeen ? `last sync ${new Date(s.lastSeen).toISOString()}` : 'from the last session / de la última sesión';
    out.push(`- Roblox Studio: \`${s.place}\` · ${s.connected ? 'live / en vivo' : seen}`);
  }
  out.push(`- Nodes: ${graph.nodes.length} (disk ${disk.length}, studio ${live.length}) · links: ${graph.links.length}`);
  out.push('');
  out.push('## How to use this map / Cómo usar este mapa');
  out.push('');
  out.push('- Find what you need here first, then open only that file. / Busca aquí primero y abre solo ese archivo.');
  out.push('- Studio scripts are mirrored read-only in `.soulgraph/studio/`; editing the mirror does nothing. / Los scripts de Studio están copiados en `.soulgraph/studio/` (solo lectura).');
  out.push('- Every node and link (with ids) is in `.soulgraph/graph.json`, one per line. / Todos los nodos y enlaces están en `.soulgraph/graph.json`.');
  out.push('');

  // Salud: lo primero que conviene saber antes de tocar nada / Health: worth knowing before touching anything
  const issues = graph.issues || [];
  if (issues.length) {
    out.push('## Health / Salud');
    out.push('');
    for (const issue of issues) out.push(`- ${issueLine(issue, byId, label)}`);
    out.push('');
  }

  // Resumen por tipo / Summary by kind
  out.push('## Summary / Resumen');
  out.push('');
  out.push('| Source | Kind | Count |');
  out.push('|---|---|---|');
  const counts = new Map();
  for (const n of graph.nodes) {
    const key = `${n.source}|${n.kind}`;
    counts.set(key, (counts.get(key) || 0) + 1);
  }
  for (const [key, count] of [...counts].sort()) {
    const [source, kind] = key.split('|');
    out.push(`| ${source} | ${kind} | ${count} |`);
  }
  out.push('');

  // Código: lo más útil para Claude / Code: the most useful part for Claude
  const scripts = live.filter((n) => ['server', 'client', 'module'].includes(n.kind));
  if (scripts.length) {
    out.push('## Studio scripts');
    out.push('');
    for (const n of scripts.sort((a, b) => label(a).localeCompare(label(b)))) {
      out.push(...codeEntry(n, label(n), mirrors.get(n.id) && `.soulgraph/studio/${mirrors.get(n.id)}`, usedBy, byId, label));
    }
    out.push('');
  }

  // Eventos: cómo hablan cliente y servidor / Events: how client and server talk
  const remotes = live.filter((n) => n.kind === 'remote');
  if (remotes.length) {
    out.push('## Events / Eventos');
    out.push('');
    for (const n of remotes.sort((a, b) => label(a).localeCompare(label(b)))) {
      const senders = graph.links.filter((l) => l.type === 'signal' && l.target === n.id).map((l) => label(byId.get(l.source)));
      const listeners = graph.links.filter((l) => l.type === 'signal' && l.source === n.id).map((l) => label(byId.get(l.target)));
      out.push(`- \`${label(n)}\` (${n.class}) — fired by: ${senders.join(', ') || '—'} · heard by: ${listeners.join(', ') || '—'}`);
    }
    out.push('');
  }

  const diskCode = disk.filter((n) => n.kind === 'code');
  if (diskCode.length) {
    out.push('## Code on disk / Código en disco');
    out.push('');
    for (const n of diskCode.sort((a, b) => a.path.localeCompare(b.path))) {
      out.push(...codeEntry(n, n.path, null, usedBy, byId, label));
    }
    out.push('');
  }

  // Estructura de Studio / Studio structure
  const services = live.filter((n) => !n.parent);
  const structure = live.filter((n) => n.kind !== 'function');
  if (services.length) {
    out.push('## Studio structure / Estructura de Studio');
    out.push('');
    out.push('_Containers up to a few levels deep, plus every script. Parts are not listed._');
    out.push('');
    const children = childrenIndex(structure);
    const walk = (n, depth) => {
      out.push(`${'  '.repeat(depth)}- ${instanceLine(n)}`);
      for (const c of children.get(n.id) || []) walk(c, depth + 1);
    };
    for (const svc of services) walk(svc, 0);
    out.push('');
  }

  // Árbol del disco / Disk tree
  out.push('## Disk / Disco');
  out.push('');
  const diskChildren = childrenIndex(disk);
  const walkDisk = (n, depth) => {
    const kids = diskChildren.get(n.id) || [];
    const folders = kids.filter((k) => k.kind === 'folder');
    const files = kids.filter((k) => k.kind !== 'folder');
    for (const f of folders) {
      out.push(`${'  '.repeat(depth)}- **${f.name}/**`);
      walkDisk(f, depth + 1);
    }
    for (const line of fileLines(files, byId)) out.push(`${'  '.repeat(depth)}- ${line}`);
  };
  const root = disk.find((n) => n.kind === 'root');
  if (root) walkDisk(root, 0);
  out.push('');

  return out.join('\n');
}

function codeEntry(n, title, mirror, usedBy, byId, label) {
  const lines = [];
  const meta = [n.kind, n.lines != null ? `${n.lines} lines` : null, n.disabled ? 'disabled' : null].filter(Boolean).join(', ');
  lines.push(`- \`${title}\` — ${meta}${mirror ? ` → \`${mirror}\`` : ''}`);
  const symbols = n.symbols || [];
  if (symbols.length) {
    const extra = symbols.length > MAX_SYMBOLS ? ` (+${symbols.length - MAX_SYMBOLS})` : '';
    lines.push(`  - defines: ${symbols.slice(0, MAX_SYMBOLS).join(', ')}${extra}`);
  }
  if (n.imports && n.imports.length) lines.push(`  - requires: ${n.imports.join(', ')}`);
  if (n.sends && n.sends.length) lines.push(`  - fires: ${n.sends.join(', ')}`);
  if (n.listens && n.listens.length) lines.push(`  - listens: ${n.listens.join(', ')}`);
  const users = usedBy.get(n.id);
  if (users && users.length) lines.push(`  - used by: ${users.map((id) => label(byId.get(id))).join(', ')}`);

  // Qué funciones de este módulo se llaman desde fuera, y desde dónde.
  // Which of this module's functions are called from outside, and from where.
  for (const symbol of symbols) {
    const callers = usedBy.get(`${n.id}#${symbol}`);
    if (callers && callers.length) lines.push(`  - ${symbol} ← ${callers.map((id) => label(byId.get(id))).join(', ')}`);
  }
  return lines;
}

function instanceLine(n) {
  const parts = [`**${n.name}**`];
  if (n.class !== 'Folder' && n.class !== n.name) parts.push(`(${n.class})`);
  if (n.children) parts.push(`· ${n.children} children`);
  if (n.tags) parts.push(`· tags: ${n.tags.join(', ')}`);
  if (n.attrs) {
    const attrs = Object.entries(n.attrs).map(([k, a]) => `${k}=${shorten(String(a && a.value !== undefined ? a.value : a), 30)}`);
    parts.push(`· attrs: ${attrs.join(', ')}`);
  }
  return parts.join(' ');
}

// Agrupa muchos archivos del mismo tipo en una línea (p. ej. 70 texturas).
// Groups many same-kind files into a single line (e.g. 70 textures).
function fileLines(files, byId) {
  const byKind = new Map();
  for (const f of files) {
    if (!byKind.has(f.kind)) byKind.set(f.kind, []);
    byKind.get(f.kind).push(f);
  }
  const lines = [];
  for (const [kind, list] of byKind) {
    if (list.length >= COLLAPSE_AT) {
      const total = list.reduce((sum, f) => sum + (f.size || 0), 0);
      const sample = list.slice(0, 6).map((f) => f.name).join(', ');
      lines.push(`${list.length} ${kind} files (${formatBytes(total)}): ${sample}, …`);
      continue;
    }
    for (const f of list) {
      const extra = [kind, formatBytes(f.size), f.lines != null ? `${f.lines} lines` : null].filter(Boolean).join(', ');
      lines.push(`${f.name} — ${extra}`);
    }
  }
  return lines;
}

function childrenIndex(nodes) {
  const index = new Map();
  for (const n of nodes) {
    if (!n.parent) continue;
    if (!index.has(n.parent)) index.set(n.parent, []);
    index.get(n.parent).push(n);
  }
  for (const list of index.values()) list.sort((a, b) => a.name.localeCompare(b.name));
  return index;
}

const ISSUE_TEXT = {
  'broken-require': (names, detail) => `**Broken require** in ${names}: no module called \`${detail}\` / require roto: no existe el módulo`,
  'duplicate-name': (names, detail) => `**Duplicate module name** \`${detail}\` (require by name is ambiguous): ${names} / nombre de módulo repetido`,
  'unused-module': (names) => `Possibly unused module (nobody requires it): ${names} / módulo posiblemente sin usar`,
  cycle: (names) => `**Circular require**: ${names} / dependencia circular`,
  'event-no-listener': (names) => `Event fired but never listened to: ${names} / evento que nadie escucha`,
  'event-no-sender': (names) => `Event listened to but never fired: ${names} / evento que nadie dispara`,
};

function issueLine(issue, byId, label) {
  const names = issue.ids.map((id) => `\`${byId.has(id) ? label(byId.get(id)) : id}\``).join(issue.type === 'cycle' ? ' → ' : ', ');
  const text = ISSUE_TEXT[issue.type];
  return text ? text(names, issue.detail) : `${issue.type}: ${names}`;
}

function formatBytes(bytes) {
  if (bytes == null) return '';
  const units = ['B', 'KB', 'MB', 'GB'];
  let value = bytes;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit++;
  }
  return `${value.toFixed(unit ? 1 : 0)} ${units[unit]}`;
}

function shorten(text, max) {
  return text.length > max ? `${text.slice(0, max - 1)}…` : text;
}

// ---------- Espejo de scripts / Script mirror ----------

function writeMirrors(dir, mirrors, sources) {
  const wanted = new Set();
  for (const [id, rel] of mirrors) {
    const file = path.join(dir, ...rel.split('/'));
    wanted.add(path.normalize(file));
    fs.mkdirSync(path.dirname(file), { recursive: true });
    writeIfChanged(file, sources.get(id));
  }
  removeStale(dir, wanted);
}

// Borra los scripts que ya no existen en Studio (solo dentro de .soulgraph/studio).
// Deletes scripts that no longer exist in Studio (only inside .soulgraph/studio).
function removeStale(dir, wanted) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      removeStale(full, wanted);
      if (!fs.readdirSync(full).length) fs.rmdirSync(full);
    } else if (!wanted.has(path.normalize(full))) {
      fs.unlinkSync(full);
    }
  }
}

function writeIfChanged(file, content) {
  try {
    if (fs.readFileSync(file, 'utf8') === content) return;
  } catch {
    // no existe todavía / doesn't exist yet
  }
  fs.writeFileSync(file, content);
}

module.exports = { writeOutputs, mapMarkdown, formatBytes };
